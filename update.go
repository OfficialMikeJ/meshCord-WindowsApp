package main

// ─────────────────────────────────────────────────────────────────────────────
//  Desktop self-updater — checks the Gitea repo for a newer release.
//
//    Repo:    https://repo.mikeshomelabservices.xyz/OfficialMikeJ/MeshCord-Desktop
//    Source:  releases published on the repo (tag_name = version)
//    UI:      the titlebar shows an Update button ONLY when latest > current
//
//  CheckForUpdate reads version.json on meshcordapp.xyz — the site mirrors
//  each repo release (the Gitea instance requires sign-in for API calls, so
//  clients can't read it directly). DownloadUpdate pulls MeshCord-Setup.exe
//  to %TEMP% and launches it — the installer upgrades Program Files.
// ─────────────────────────────────────────────────────────────────────────────

import (
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

// AppVersion is bumped per release — must match the tag pushed to the repo.
const AppVersion = "2026.10.03"

// Release feed on the website — regenerated by pack-bundle.sh every release,
// always in step with the staged MeshCord-Setup.exe.
const updateFeedURL      = "https://meshcordapp.xyz/files/version.json"
const updateInstallerURL = "https://meshcordapp.xyz/files/MeshCord-Setup.exe"

type UpdateInfo struct {
	CurrentVersion   string `json:"currentVersion"`
	LatestVersion    string `json:"latestVersion"`
	UpdateAvailable  bool   `json:"updateAvailable"`
	ReleaseURL       string `json:"releaseUrl"`
	InstallerURL     string `json:"installerUrl"` // direct asset link for MeshCord-Setup.exe
	PublishedAt      string `json:"publishedAt"`
}

// version.json as written by pack-bundle.sh.
type versionMeta struct {
	Version   string `json:"version"`
	BuiltAt   string `json:"builtAt"`
}

var updateHTTP = &http.Client{Timeout: 10 * time.Second}

// compareVersions returns true when remote is strictly newer than local.
// Dotted numeric versions ("2026.10.03" > "2026.10.02"); a leading "v" is
// ignored on both sides.
func compareVersions(remote, local string) bool {
	norm := func(v string) []int {
		v = strings.TrimPrefix(strings.TrimSpace(v), "v")
		parts := strings.FieldsFunc(v, func(r rune) bool { return r == '.' || r == '-' })
		out := make([]int, len(parts))
		for i, p := range parts {
			out[i], _ = strconv.Atoi(p)
		}
		return out
	}
	r, l := norm(remote), norm(local)
	for i := 0; i < len(r) || i < len(l); i++ {
		var rv, lv int
		if i < len(r) {
			rv = r[i]
		}
		if i < len(l) {
			lv = l[i]
		}
		if rv != lv {
			return rv > lv
		}
	}
	return false
}

// CheckForUpdate queries the site's version.json and reports whether the
// titlebar Update button should appear.
func (a *App) CheckForUpdate() (UpdateInfo, error) {
	info := UpdateInfo{CurrentVersion: AppVersion}

	resp, err := updateHTTP.Get(updateFeedURL)
	if err != nil {
		return info, fmt.Errorf("could not reach update feed: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode == http.StatusNotFound {
		return info, nil // no release staged yet — no update
	}
	if resp.StatusCode != http.StatusOK {
		return info, fmt.Errorf("update check failed: HTTP %d", resp.StatusCode)
	}

	var meta versionMeta
	if err := json.NewDecoder(resp.Body).Decode(&meta); err != nil {
		return info, fmt.Errorf("bad version payload: %w", err)
	}

	info.LatestVersion = meta.Version
	info.ReleaseURL    = "https://repo.mikeshomelabservices.xyz/OfficialMikeJ/MeshCord-Desktop/releases"
	info.PublishedAt   = meta.BuiltAt
	info.InstallerURL  = updateInstallerURL
	info.UpdateAvailable = compareVersions(info.LatestVersion, AppVersion)
	return info, nil
}

// DownloadUpdate fetches the installer asset and launches it. The installer
// takes over: it closes the running app, upgrades Program Files, done.
func (a *App) DownloadUpdate() (string, error) {
	info, err := a.CheckForUpdate()
	if err != nil {
		return "", err
	}
	if !info.UpdateAvailable || info.InstallerURL == "" {
		return "", fmt.Errorf("no update available")
	}

	resp, err := updateHTTP.Get(info.InstallerURL)
	if err != nil {
		return "", fmt.Errorf("download failed: %w", err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("download failed: HTTP %d", resp.StatusCode)
	}

	dest := filepath.Join(os.TempDir(), "MeshCord-Setup.exe")
	f, err := os.Create(dest)
	if err != nil {
		return "", err
	}
	if _, err := io.Copy(f, resp.Body); err != nil {
		f.Close()
		return "", err
	}
	f.Close()

	cmd := exec.Command(dest)
	if err := cmd.Start(); err != nil {
		return "", fmt.Errorf("could not launch installer: %w", err)
	}
	return dest, nil
}
